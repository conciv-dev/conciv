import type {Skill} from '@conciv/plugin'

const OPERATIONS = [
  ['canvas_read', 'list the elements of the published canvas, or of the hidden draft with scope "draft"'],
  ['canvas_svg', 'draw by writing SVG markup; the canvas converts it into editable elements in the draft'],
  ['canvas_draw', 'add element skeletons (rectangle, ellipse, diamond, text, arrow, line) to the draft'],
  ['canvas_diagram', 'render a Mermaid diagram into the draft'],
  ['canvas_connect', 'draw a binding arrow between two elements by elementId'],
  ['canvas_update', 'patch the fields of an element, in the draft first, else on the published canvas'],
  ['canvas_preview', 'a fast, approximate PNG of the draft rendered by the engine'],
  ['canvas_export', 'export the canvas as json, or as a real PNG rendered by the open canvas tab'],
  ['canvas_commit', 'publish the draft to the shared canvas'],
  ['canvas_discard', 'throw the draft away'],
  ['canvas_delete', 'remove one element; the user is asked to confirm'],
  ['canvas_clear', 'wipe every element off the published canvas; the user is asked to confirm'],
  ['comment_create', 'pin a comment to the canvas, optionally anchored to a source element'],
  ['comment_reply', 'reply to a comment in its thread'],
  ['comment_read', 'read a comment and its replies'],
  ['comment_list', 'list the top-level comments, by file or status'],
  ['comment_move', 'move a comment pin'],
  ['comment_resolve', 'mark a comment resolved once addressed; the user is asked to confirm'],
  [
    'comment_delete',
    'remove a comment, or a whole thread and its pin when it is the root; the user is asked to confirm',
  ],
  ['pin_set_state', 'lock a pin to its element, or let it float at an offset'],
  ['anchor_resolve', 'check whether a source-linked comment still points at its element'],
  ['element_reference', 'locate a component by name in a file, to anchor a comment to it'],
]

