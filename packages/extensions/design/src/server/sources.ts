import type {Source} from '@conciv/extension'
import type {designTables} from './tables.js'

export function designSources(tables: ReturnType<typeof designTables>): Record<string, Source> {
  const {
    targets,
    rounds,
    missing,
    candidates,
    widths,
    regions,
    rows,
    fom,
    votes,
    tool_calls: toolCalls,
    runs,
    labels,
    notes,
  } = tables
  return {
    targets: {
      table: targets,
      fields: {
        target: targets.target_id,
        run: targets.run_id,
        session: targets.session,
        link: targets.link,
        route: targets.route,
        width: targets.width,
        height: targets.height,
        scale: targets.scale,
        image: targets.image,
        at: targets.at,
      },
    },
    rounds: {
      table: rounds,
      fields: {
        seq: rounds.seq,
        target: rounds.target_id,
        run: rounds.run_id,
        round: rounds.round,
        much: rounds.much,
        noticeably: rounds.noticeably,
        slightly: rounds.slightly,
        pins: rounds.pins,
        other: rounds.other,
        reflow: rounds.reflow,
        rows_count: rounds.rows_count,
        nodes: rounds.nodes,
        mapped: rounds.mapped,
        rendered: rounds.rendered,
        revoted: rounds.revoted,
        pixel_share: rounds.pixel_share,
        pixel_before: rounds.pixel_before,
        closed: rounds.closed,
        opened: rounds.opened,
        kept: rounds.kept,
        gained: rounds.gained,
        lost: rounds.lost,
        changed_ratio: rounds.changed_ratio,
        changed_regions: rounds.changed_regions,
        note: rounds.note,
        tree: rounds.tree,
        verdict: rounds.verdict,
        unsettled: rounds.unsettled,
        live: rounds.live,
        diff: rounds.diff,
        at: rounds.at,
      },
    },
    missing: {
      table: missing,
      fields: {
        seq: missing.seq,
        target: missing.target_id,
        run: missing.run_id,
        round: missing.round,
        node: missing.node,
        kind: missing.kind,
      },
    },
    candidates: {
      table: candidates,
      fields: {
        seq: candidates.seq,
        target: candidates.target_id,
        run: candidates.run_id,
        round: candidates.round,
        node: candidates.node,
        selector: candidates.selector,
        score: candidates.score,
      },
    },
    widths: {
      table: widths,
      fields: {
        seq: widths.seq,
        target: widths.target_id,
        run: widths.run_id,
        round: widths.round,
        width: widths.width,
        from: widths.from,
        root_height: widths.root_height,
        overflow_x: widths.overflow_x,
      },
    },
    regions: {
      table: regions,
      fields: {
        seq: regions.seq,
        target: regions.target_id,
        run: regions.run_id,
        round: regions.round,
        x: regions.x,
        y: regions.y,
        width: regions.width,
        height: regions.height,
        id: regions.id,
        node: regions.node,
        name: regions.name,
        source: regions.source,
        overlap: regions.overlap,
        truncated: regions.truncated,
      },
    },
    rows: {
      table: rows,
      fields: {
        seq: rows.seq,
        target: rows.target_id,
        run: rows.run_id,
        round: rows.round,
        id: rows.id,
        node: rows.node,
        source: rows.source,
        selector: rows.selector,
        kind: rows.kind,
        name: rows.name,
        magnitude: rows.magnitude,
        width: rows.width,
        text: rows.text,
        confidence: rows.confidence,
        margin: rows.margin,
        repeat: rows.repeat,
        at: rows.at,
      },
    },
    fom: {
      table: fom,
      order: [
        {field: 'round', dir: 'asc'},
        {field: 'seq', dir: 'asc'},
      ],
      fields: {
        seq: fom.seq,
        target: fom.target_id,
        run: fom.run_id,
        id: fom.id,
        node: fom.node,
        name: fom.name,
        instance: fom.instance,
        source: fom.source,
        confidence: fom.confidence,
        margin: fom.margin,
        round: fom.round,
        voted_round: fom.voted_round,
        revoted_round: fom.revoted_round,
        reason: fom.reason,
        at: fom.at,
      },
    },
    votes: {
      table: votes,
      fields: {
        seq: votes.seq,
        target: votes.target_id,
        run: votes.run_id,
        round: votes.round,
        node: votes.node,
        name: votes.name,
        candidate: votes.candidate,
        path: votes.path,
        dom: votes.dom,
        src: votes.src,
        cssom: votes.cssom,
        total: votes.total,
        won: votes.won,
        at: votes.at,
      },
    },
    tool_calls: {
      table: toolCalls,
      fields: {
        seq: toolCalls.seq,
        target: toolCalls.target_id,
        run: toolCalls.run_id,
        tool: toolCalls.tool,
        round: toolCalls.round,
        input: toolCalls.input,
        reply_bytes: toolCalls.reply_bytes,
        duration_ms: toolCalls.duration_ms,
        error: toolCalls.error,
        at: toolCalls.at,
      },
    },
    runs: {
      table: runs,
      fields: {
        seq: runs.run_id,
        run: runs.run_id,
        target: runs.target_id,
        model: runs.model,
        prompt_head: runs.prompt_head,
        started: runs.started,
        ended: runs.ended,
        cost: runs.cost,
        verdict: runs.verdict,
      },
    },
    labels: {
      table: labels,
      writable: true,
      fields: {
        seq: labels.seq,
        target: labels.target_id,
        run: labels.run_id,
        round: labels.round,
        node: labels.node,
        id: labels.id,
        verdict: labels.verdict,
        by: labels.by,
        note: labels.note,
        at: labels.at,
      },
    },
    notes: {
      table: notes,
      writable: true,
      fields: {
        seq: notes.seq,
        target: notes.target_id,
        run: notes.run_id,
        round: notes.round,
        text: notes.text,
        at: notes.at,
      },
    },
  }
}
