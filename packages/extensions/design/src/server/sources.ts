import type {Source} from '@conciv/extension'
import type {designTables} from './tables.js'

export function designSources(tables: ReturnType<typeof designTables>): Record<string, Source> {
  const {
    targets,
    rounds,
    missing,
    candidates,
    widths,
    regions,
    rows,
    fom_nodes: fomNodes,
    nodes,
    votes,
    tool_calls: toolCalls,
    runs,
    labels,
    notes,
  } = tables
  return {
    targets: {
      table: targets,
      fields: {
        target: targets.target_id,
        run: targets.run_id,
        session: targets.session,
        link: targets.link,
        route: targets.route,
        width: targets.width,
        height: targets.height,
        scale: targets.scale,
        image: targets.image,
        at: targets.at,
      },
    },
    rounds: {
      table: rounds,
      fields: {
        seq: rounds.seq,
        target: rounds.target_id,
        run: rounds.run_id,
        round: rounds.round,
        much: rounds.much,
        noticeably: rounds.noticeably,
        slightly: rounds.slightly,
        pins: rounds.pins,
        other: rounds.other,
        reflow: rounds.reflow,
        paint: rounds.paint,
        rows_count: rounds.rows_count,
        nodes: rounds.nodes,
        mapped: rounds.mapped,
        rendered: rounds.rendered,
        revoted: rounds.revoted,
        pixel_share: rounds.pixel_share,
        pixel_before: rounds.pixel_before,
        closed: rounds.closed,
        opened: rounds.opened,
        kept: rounds.kept,
        gained: rounds.gained,
        lost: rounds.lost,
        changed_ratio: rounds.changed_ratio,
        changed_regions: rounds.changed_regions,
        note: rounds.note,
        tree: rounds.tree,
        verdict: rounds.verdict,
        unsettled: rounds.unsettled,
        live: rounds.live,
        diff: rounds.diff,
        at: rounds.at,
      },
    },
    missing: {
      table: missing,
      fields: {
        seq: missing.seq,
        target: missing.target_id,
        run: missing.run_id,
        round: missing.round,
        node: missing.node,
        kind: missing.kind,
      },
    },
    candidates: {
      table: candidates,
      fields: {
        seq: candidates.seq,
        target: candidates.target_id,
        run: candidates.run_id,
        round: candidates.round,
        node: candidates.node,
        selector: candidates.selector,
        score: candidates.score,
      },
    },
    widths: {
      table: widths,
      fields: {
        seq: widths.seq,
        target: widths.target_id,
        run: widths.run_id,
        round: widths.round,
        width: widths.width,
        from: widths.from,
        root_height: widths.root_height,
        overflow_x: widths.overflow_x,
      },
    },
    regions: {
      table: regions,
      fields: {
        seq: regions.seq,
        target: regions.target_id,
        run: regions.run_id,
        round: regions.round,
        x: regions.x,
        y: regions.y,
        width: regions.width,
        height: regions.height,
        id: regions.id,
        node: regions.node,
        name: regions.name,
        source: regions.source,
        overlap: regions.overlap,
        truncated: regions.truncated,
      },
    },
    rows: {
      table: rows,
      fields: {
        seq: rows.seq,
        target: rows.target_id,
        run: rows.run_id,
        round: rows.round,
        id: rows.id,
        node: rows.node,
        source: rows.source,
        selector: rows.selector,
        kind: rows.kind,
        name: rows.name,
        magnitude: rows.magnitude,
        width: rows.width,
        text: rows.text,
        token: rows.token,
        confidence: rows.confidence,
        margin: rows.margin,
        repeat: rows.repeat,
        at: rows.at,
      },
    },
    fom: {
      table: fomNodes,
      order: [
        {field: 'round', dir: 'asc'},
        {field: 'seq', dir: 'asc'},
      ],
      fields: {
        seq: fomNodes.seq,
        target: fomNodes.target_id,
        run: fomNodes.run_id,
        id: fomNodes.id,
        node: fomNodes.node,
        name: fomNodes.name,
        instance: fomNodes.instance,
        source: fomNodes.source,
        confidence: fomNodes.confidence,
        margin: fomNodes.margin,
        round: fomNodes.round,
        voted_round: fomNodes.voted_round,
        revoted_round: fomNodes.revoted_round,
        reason: fomNodes.reason,
        at: fomNodes.at,
        type: fomNodes.type,
        within: fomNodes.within,
        depth: fomNodes.depth,
        x: fomNodes.x,
        y: fomNodes.y,
        w: fomNodes.w,
        h: fomNodes.h,
        fill_kind: fomNodes.fill_kind,
        fill: fomNodes.fill,
        fill_opacity: fomNodes.fill_opacity,
        stroke: fomNodes.stroke,
        stroke_weight: fomNodes.stroke_weight,
        radius: fomNodes.radius,
        font_family: fomNodes.font_family,
        font_weight: fomNodes.font_weight,
        font_size: fomNodes.font_size,
        line_height: fomNodes.line_height,
        text_align: fomNodes.text_align,
        text: fomNodes.text,
        opacity: fomNodes.opacity,
        image: fomNodes.image,
        asset: fomNodes.asset,
        token_fill: fomNodes.token_fill,
        token_stroke: fomNodes.token_stroke,
        token_radius: fomNodes.token_radius,
        token_font: fomNodes.token_font,
        token_gap: fomNodes.token_gap,
        token_padding: fomNodes.token_padding,
      },
    },
    nodes: {
      table: nodes,
      fields: {
        seq: nodes.seq,
        target: nodes.target_id,
        run: nodes.run_id,
        node: nodes.node,
        name: nodes.name,
        type: nodes.type,
        within: nodes.within,
        depth: nodes.depth,
        x: nodes.x,
        y: nodes.y,
        w: nodes.w,
        h: nodes.h,
        fill_kind: nodes.fill_kind,
        fill: nodes.fill,
        fill_opacity: nodes.fill_opacity,
        stroke: nodes.stroke,
        stroke_weight: nodes.stroke_weight,
        radius: nodes.radius,
        font_family: nodes.font_family,
        font_weight: nodes.font_weight,
        font_size: nodes.font_size,
        line_height: nodes.line_height,
        text_align: nodes.text_align,
        text: nodes.text,
        opacity: nodes.opacity,
        image: nodes.image,
        asset: nodes.asset,
        token_fill: nodes.token_fill,
        token_stroke: nodes.token_stroke,
        token_radius: nodes.token_radius,
        token_font: nodes.token_font,
        token_gap: nodes.token_gap,
        token_padding: nodes.token_padding,
      },
    },
    votes: {
      table: votes,
      fields: {
        seq: votes.seq,
        target: votes.target_id,
        run: votes.run_id,
        round: votes.round,
        node: votes.node,
        name: votes.name,
        candidate: votes.candidate,
        path: votes.path,
        dom: votes.dom,
        src: votes.src,
        cssom: votes.cssom,
        total: votes.total,
        won: votes.won,
        at: votes.at,
      },
    },
    tool_calls: {
      table: toolCalls,
      fields: {
        seq: toolCalls.seq,
        target: toolCalls.target_id,
        run: toolCalls.run_id,
        tool: toolCalls.tool,
        round: toolCalls.round,
        input: toolCalls.input,
        reply_bytes: toolCalls.reply_bytes,
        duration_ms: toolCalls.duration_ms,
        error: toolCalls.error,
        at: toolCalls.at,
      },
    },
    runs: {
      table: runs,
      fields: {
        seq: runs.run_id,
        run: runs.run_id,
        target: runs.target_id,
        model: runs.model,
        prompt_head: runs.prompt_head,
        started: runs.started,
        ended: runs.ended,
        cost: runs.cost,
        verdict: runs.verdict,
      },
    },
    labels: {
      table: labels,
      writable: true,
      fields: {
        seq: labels.seq,
        target: labels.target_id,
        run: labels.run_id,
        round: labels.round,
        node: labels.node,
        id: labels.id,
        verdict: labels.verdict,
        by: labels.by,
        note: labels.note,
        at: labels.at,
      },
    },
    notes: {
      table: notes,
      writable: true,
      fields: {
        seq: notes.seq,
        target: notes.target_id,
        run: notes.run_id,
        round: notes.round,
        text: notes.text,
        at: notes.at,
      },
    },
  }
}
