import type {ExtensionSource} from '@conciv/extension'
import type {designTables} from './tables.js'

export function designSources(tables: ReturnType<typeof designTables>): Record<string, ExtensionSource> {
  const {targets, rounds, rows, fom, votes, tool_calls: toolCalls, runs, labels, notes} = tables
  return {
    targets: {
      table: targets,
      fields: {
        target: targets.target_id,
        run: targets.run_id,
        session: targets.session,
        link: targets.link,
        route: targets.route,
        width: targets.width,
        height: targets.height,
        scale: targets.scale,
        image: targets.image,
        at: targets.at,
      },
    },
    rounds: {
      table: rounds,
      fields: {
        seq: rounds.seq,
        target: rounds.target_id,
        run: rounds.run_id,
        round: rounds.round,
        counts: rounds.counts,
        coverage: rounds.coverage,
        reflow_detail: rounds.reflow,
        much: {column: rounds.counts, path: '$.much'},
        noticeably: {column: rounds.counts, path: '$.noticeably'},
        slightly: {column: rounds.counts, path: '$.slightly'},
        pins: {column: rounds.counts, path: '$.pins'},
        reflow: {column: rounds.counts, path: '$.reflow'},
        rows_count: {column: rounds.counts, path: '$.rows'},
        rendered: {column: rounds.coverage, path: '$.rendered'},
        missing: {column: rounds.coverage, path: '$.missing'},
        pixel_share: rounds.pixel_share,
        tree: rounds.tree,
        live: rounds.live,
        diff: rounds.diff,
        at: rounds.at,
      },
    },
    rows: {
      table: rows,
      fields: {
        seq: rows.seq,
        target: rows.target_id,
        run: rows.run_id,
        round: rows.round,
        id: rows.id,
        node: rows.node,
        source: rows.source,
        selector: rows.selector,
        kind: rows.kind,
        name: rows.name,
        magnitude: rows.magnitude,
        width: rows.width,
        text: rows.text,
        confidence: rows.confidence,
        margin: rows.margin,
        at: rows.at,
      },
    },
    fom: {
      table: fom,
      fields: {
        seq: fom.seq,
        target: fom.target_id,
        run: fom.run_id,
        id: fom.id,
        node: fom.node,
        instance: fom.instance,
        confidence: fom.confidence,
        margin: fom.margin,
        round: fom.round,
        revoted_round: fom.revoted_round,
        reason: fom.reason,
        at: fom.at,
      },
    },
    votes: {
      table: votes,
      fields: {
        seq: votes.seq,
        target: votes.target_id,
        run: votes.run_id,
        round: votes.round,
        node: votes.node,
        candidate: votes.candidate,
        path: votes.path,
        dom: votes.dom,
        src: votes.src,
        cssom: votes.cssom,
        total: votes.total,
        won: votes.won,
        at: votes.at,
      },
    },
    tool_calls: {
      table: toolCalls,
      fields: {
        seq: toolCalls.seq,
        target: toolCalls.target_id,
        run: toolCalls.run_id,
        tool: toolCalls.tool,
        input: toolCalls.input,
        reply_bytes: toolCalls.reply_bytes,
        duration_ms: toolCalls.duration_ms,
        error: toolCalls.error,
        at: toolCalls.at,
      },
    },
    runs: {
      table: runs,
      fields: {
        seq: runs.run_id,
        run: runs.run_id,
        target: runs.target_id,
        model: runs.model,
        prompt_head: runs.prompt_head,
        started: runs.started,
        ended: runs.ended,
        cost: runs.cost,
        verdict: runs.verdict,
      },
    },
    labels: {
      table: labels,
      writable: true,
      fields: {
        seq: labels.seq,
        target: labels.target_id,
        run: labels.run_id,
        round: labels.round,
        node: labels.node,
        id: labels.id,
        verdict: labels.verdict,
        by: labels.by,
        note: labels.note,
        at: labels.at,
      },
    },
    notes: {
      table: notes,
      writable: true,
      fields: {
        seq: notes.seq,
        target: notes.target_id,
        run: notes.run_id,
        round: notes.round,
        text: notes.text,
        at: notes.at,
      },
    },
  }
}
