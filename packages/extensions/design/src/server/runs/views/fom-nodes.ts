import {sql} from 'drizzle-orm'
import {integer, real, sqliteView, text} from 'drizzle-orm/sqlite-core'

export const fomNodesView = sqliteView('fom_nodes', {
  seq: integer().notNull(),
  target_id: text().notNull(),
  run_id: integer().notNull(),
  id: text().notNull(),
  node: text().notNull(),
  name: text(),
  instance: text(),
  source: text(),
  site: text(),
  confidence: real().notNull(),
  margin: real().notNull(),
  round: integer().notNull(),
  voted_round: integer(),
  revoted_round: integer(),
  reason: text(),
  at: integer().notNull(),
  type: text(),
  within: text(),
  depth: integer(),
  x: real(),
  y: real(),
  w: real(),
  h: real(),
  fill_kind: text(),
  fill: text(),
  fill_opacity: real(),
  stroke: text(),
  stroke_weight: real(),
  radius: real(),
  font_family: text(),
  font_weight: real(),
  font_size: real(),
  line_height: real(),
  text_align: text(),
  text: text(),
  opacity: real(),
  image: integer({mode: 'boolean'}),
  asset: text(),
  token_fill: text(),
  token_stroke: text(),
  token_radius: text(),
  token_font: text(),
  token_gap: text(),
  token_padding: text(),
}).as(sql`SELECT f.seq, f.target_id, f.run_id, f.id, f.node, f.name, f.instance, f.source, f.site, f.confidence,
  f.margin, f.round, f.voted_round, f.revoted_round, f.reason, f.at, n.type, n.within, n.depth, n.x, n.y, n.w, n.h,
  n.fill_kind, n.fill, n.fill_opacity, n.stroke, n.stroke_weight, n.radius, n.font_family, n.font_weight, n.font_size,
  n.line_height, n.text_align, n.text, n.opacity, n.image, n.asset, n.token_fill, n.token_stroke, n.token_radius,
  n.token_font, n.token_gap, n.token_padding
FROM design_fom f
LEFT JOIN design_nodes n ON n.run_id = f.run_id AND n.target_id = f.target_id AND n.node = f.node`)
