import {sql} from 'drizzle-orm'
import {check, integer, real, text, type SQLiteTableFn} from 'drizzle-orm/sqlite-core'
import {DESIGN_VERDICTS, type Design, type IdTree} from '../shared/defs.js'

export function designTables(table: SQLiteTableFn) {
  return {
    targets: table('targets', {
      target_id: text().primaryKey(),
      run_id: integer(),
      session: text().notNull(),
      link: text().notNull(),
      route: text(),
      width: real().notNull(),
      height: real().notNull(),
      scale: real().notNull(),
      design: text({mode: 'json'}).$type<Design>().notNull(),
      image: text().notNull(),
      unsettled: integer().notNull().default(0),
      at: integer().notNull(),
    }),
    rounds: table('rounds', {
      seq: integer().primaryKey({autoIncrement: true}),
      target_id: text().notNull(),
      run_id: integer(),
      round: integer().notNull(),
      much: integer().notNull().default(0),
      noticeably: integer().notNull().default(0),
      slightly: integer().notNull().default(0),
      pins: integer().notNull().default(0),
      other: integer().notNull().default(0),
      reflow: integer().notNull().default(0),
      paint: integer().notNull().default(0),
      rows_count: integer().notNull().default(0),
      nodes: integer().notNull().default(0),
      mapped: integer().notNull().default(0),
      rendered: integer().notNull().default(0),
      revoted: integer().notNull().default(0),
      pixel_share: real(),
      pixel_before: real(),
      closed: integer(),
      opened: integer(),
      kept: integer(),
      gained: integer(),
      lost: integer(),
      changed_ratio: real(),
      changed_regions: integer(),
      note: text(),
      tree: text().notNull(),
      verdict: text(),
      unsettled: text(),
      live: text(),
      diff: text(),
      ids: text({mode: 'json'}).$type<IdTree>(),
      at: integer().notNull(),
    }),
    missing: table('missing', {
      seq: integer().primaryKey({autoIncrement: true}),
      target_id: text().notNull(),
      run_id: integer(),
      round: integer().notNull(),
      node: text().notNull(),
      kind: text({enum: COVERAGE_LISTS}).notNull(),
    }),
    candidates: table('candidates', {
      seq: integer().primaryKey({autoIncrement: true}),
      target_id: text().notNull(),
      run_id: integer(),
      round: integer().notNull(),
      node: text().notNull(),
      selector: text().notNull(),
      score: real().notNull(),
    }),
    widths: table('widths', {
      seq: integer().primaryKey({autoIncrement: true}),
      target_id: text().notNull(),
      run_id: integer(),
      round: integer().notNull(),
      width: real().notNull(),
      from: text().notNull(),
      root_height: real().notNull(),
      overflow_x: integer({mode: 'boolean'}).notNull(),
    }),
    regions: table('regions', {
      seq: integer().primaryKey({autoIncrement: true}),
      target_id: text().notNull(),
      run_id: integer(),
      round: integer().notNull(),
      x: real().notNull(),
      y: real().notNull(),
      width: real().notNull(),
      height: real().notNull(),
      id: text(),
      node: text(),
      name: text(),
      source: text(),
      overlap: real(),
      truncated: integer({mode: 'boolean'}).notNull(),
    }),
    rows: table('rows', {
      seq: integer().primaryKey({autoIncrement: true}),
      target_id: text().notNull(),
      run_id: integer(),
      round: integer().notNull(),
      id: text(),
      node: text().notNull(),
      source: text(),
      selector: text(),
      kind: text().notNull(),
      name: text().notNull(),
      magnitude: text().notNull(),
      width: real(),
      text: text().notNull(),
      token: text(),
      confidence: real(),
      margin: real(),
      repeat: integer().notNull().default(0),
      at: integer().notNull(),
    }),
    fom: table('fom', {
      seq: integer().primaryKey({autoIncrement: true}),
      target_id: text().notNull(),
      run_id: integer(),
      id: text().notNull(),
      node: text().notNull(),
      name: text(),
      instance: text(),
      source: text(),
      confidence: real().notNull(),
      margin: real().notNull(),
      round: integer().notNull(),
      voted_round: integer(),
      revoted_round: integer(),
      reason: text(),
      at: integer().notNull(),
    }),
    nodes: table('nodes', {
      seq: integer().primaryKey({autoIncrement: true}),
      target_id: text().notNull(),
      run_id: integer(),
      node: text().notNull(),
      type: text().notNull(),
      name: text().notNull(),
      within: text(),
      depth: integer().notNull(),
      x: real().notNull(),
      y: real().notNull(),
      w: real().notNull(),
      h: real().notNull(),
      fill_kind: text({enum: FILL_KINDS}).notNull(),
      fill: text(),
      fill_opacity: real(),
      stroke: text(),
      stroke_weight: real(),
      radius: real(),
      font_family: text(),
      font_weight: real(),
      font_size: real(),
      line_height: real(),
      text_align: text(),
      text: text(),
      opacity: real(),
      image: integer({mode: 'boolean'}).notNull(),
      asset: text(),
      token_fill: text(),
      token_stroke: text(),
      token_radius: text(),
      token_font: text(),
      token_gap: text(),
      token_padding: text(),
    }),
    fom_nodes: table('fom_nodes', {
      seq: integer().notNull(),
      target_id: text().notNull(),
      run_id: integer(),
      id: text().notNull(),
      node: text().notNull(),
      name: text(),
      instance: text(),
      source: text(),
      confidence: real().notNull(),
      margin: real().notNull(),
      round: integer().notNull(),
      voted_round: integer(),
      revoted_round: integer(),
      reason: text(),
      at: integer().notNull(),
      type: text(),
      within: text(),
      depth: integer(),
      x: real(),
      y: real(),
      w: real(),
      h: real(),
      fill_kind: text({enum: FILL_KINDS}),
      fill: text(),
      fill_opacity: real(),
      stroke: text(),
      stroke_weight: real(),
      radius: real(),
      font_family: text(),
      font_weight: real(),
      font_size: real(),
      line_height: real(),
      text_align: text(),
      text: text(),
      opacity: real(),
      image: integer({mode: 'boolean'}),
      asset: text(),
      token_fill: text(),
      token_stroke: text(),
      token_radius: text(),
      token_font: text(),
      token_gap: text(),
      token_padding: text(),
    }),
    votes: table('votes', {
      seq: integer().primaryKey({autoIncrement: true}),
      target_id: text().notNull(),
      run_id: integer(),
      round: integer().notNull(),
      node: text().notNull(),
      name: text(),
      candidate: text().notNull(),
      path: text().notNull(),
      dom: real().notNull(),
      src: real().notNull(),
      cssom: real().notNull(),
      total: real().notNull(),
      won: integer({mode: 'boolean'}).notNull(),
      at: integer().notNull(),
    }),
    tool_calls: table('tool_calls', {
      seq: integer().primaryKey({autoIncrement: true}),
      target_id: text(),
      run_id: integer(),
      tool: text().notNull(),
      round: integer(),
      input: text({mode: 'json'}).$type<unknown>(),
      reply_bytes: integer(),
      duration_ms: integer().notNull(),
      error: text(),
      at: integer().notNull(),
    }),
    runs: table('runs', {
      run_id: integer().primaryKey({autoIncrement: true}),
      target_id: text(),
      model: text().notNull(),
      prompt_head: text().notNull(),
      started: integer().notNull(),
      ended: integer(),
      cost: real(),
      verdict: text(),
    }),
    labels: table(
      'labels',
      {
        seq: integer().primaryKey({autoIncrement: true}),
        target_id: text().notNull(),
        run_id: integer(),
        round: integer(),
        node: text().notNull(),
        id: text(),
        verdict: text({enum: DESIGN_VERDICTS}).notNull(),
        by: text().notNull(),
        note: text(),
        at: integer().notNull().default(NOW_MS),
      },
      (self) => [check('verdict', sql`${self.verdict} in ('right', 'wrong')`)],
    ),
    notes: table('notes', {
      seq: integer().primaryKey({autoIncrement: true}),
      target_id: text().notNull(),
      run_id: integer(),
      round: integer(),
      text: text().notNull(),
      at: integer().notNull().default(NOW_MS),
    }),
  }
}

const COVERAGE_LISTS = ['missing', 'not_rendered', 'dupe'] as const

const FILL_KINDS = ['solid', 'gradient', 'image', 'none'] as const

const NOW_MS = sql`(cast(unixepoch('subsec') * 1000 as integer))`
