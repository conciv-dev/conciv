import {inArray, sql} from 'drizzle-orm'
import {
  check,
  foreignKey,
  index,
  integer,
  primaryKey,
  real,
  text,
  uniqueIndex,
  type SQLiteColumn,
  type SQLiteTableFn,
} from 'drizzle-orm/sqlite-core'
import type {TokenUsage} from '@conciv/protocol/usage-types'
import {BROKEN_BY, DESIGN_VERDICTS, ROUND_STATES, WIDGETS, type Design} from '../shared/defs.js'
import {DESIGN_TOOLS} from '../shared/design-tools.js'
import {MAGNITUDES} from '../shared/magnitudes.js'
import {RUN_VERDICTS} from '../shared/run-verdicts.js'
import type {ToolReply} from '../shared/tool-reply.js'

export function designTables(table: SQLiteTableFn) {
  const runId = () => integer().notNull()
  const session = () => text().notNull()
  const keyOf = (self: Keyed): Key => [self.run_id, self.target_id]
  const ofRun = (self: {run_id: SQLiteColumn}) =>
    foreignKey({columns: [self.run_id], foreignColumns: [runs.run_id]}).onDelete('cascade')
  const owned = (self: Keyed) => [
    ofRun(self),
    foreignKey({columns: keyOf(self), foreignColumns: keyOf(targets)}).onDelete('cascade'),
  ]
  const inRound = (self: Rounded) => [
    ...owned(self),
    foreignKey({columns: [...keyOf(self), self.round], foreignColumns: [...keyOf(rounds), rounds.round]}).onDelete(
      'cascade',
    ),
  ]
  const byRound = (name: string) => (self: Rounded) => [
    ...inRound(self),
    index(`${name}_by_round`).on(self.run_id, self.target_id, self.round),
  ]
  const runs = table(
    'runs',
    {
      run_id: integer().primaryKey({autoIncrement: true}),
      target_id: text(),
      model: text(),
      prompt_head: text(),
      started: integer().notNull(),
      last_at: integer(),
      cost: real(),
      verdict: text({enum: RUN_VERDICTS}),
      project_key: text(),
      branch: text(),
      head: text(),
      tools_head: text(),
      tools_version: text(),
      tools_fingerprint: text(),
      session: text(),
      harness: text(),
      agent_id: text(),
      usage: text({mode: 'json'}).$type<TokenUsage>(),
      error: text(),
      error_code: text(),
      harness_session_id: text(),
    },
    (self) => [
      index('runs_by_session').on(self.session),
      index('runs_by_harness_session').on(self.harness_session_id),
      check('runs_verdict', inArray(self.verdict, [...RUN_VERDICTS]).inlineParams()),
    ],
  )
  const targets = table(
    'targets',
    {
      target_id: text().notNull(),
      run_id: runId(),
      session: text().notNull(),
      link: text().notNull(),
      route: text(),
      width: real().notNull(),
      height: real().notNull(),
      scale: real().notNull(),
      design: text({mode: 'json'}).$type<Design>().notNull(),
      image: text().notNull(),
      widget: text({enum: WIDGETS}).notNull().default('hidden'),
      unsettled: integer().notNull().default(0),
      lead: text(),
      at: integer().notNull(),
    },
    (self) => [
      primaryKey({columns: keyOf(self)}),
      ofRun(self),
      check('targets_widget', inArray(self.widget, [...WIDGETS]).inlineParams()),
    ],
  )
  const rounds = table(
    'rounds',
    {
      seq: integer().primaryKey({autoIncrement: true}),
      target_id: text().notNull(),
      run_id: runId(),
      session: session(),
      check: integer().notNull(),
      round: integer(),
      state: text({enum: ROUND_STATES}).notNull(),
      same_as: integer(),
      much: integer().notNull().default(0),
      noticeably: integer().notNull().default(0),
      slightly: integer().notNull().default(0),
      pins: integer().notNull().default(0),
      other: integer().notNull().default(0),
      reflow: integer().notNull().default(0),
      paint: integer().notNull().default(0),
      drift: integer().notNull().default(0),
      rows_count: integer().notNull().default(0),
      nodes: integer().notNull().default(0),
      mapped: integer().notNull().default(0),
      rendered: integer().notNull().default(0),
      revoted: integer().notNull().default(0),
      pixel_share: real(),
      pixel_before: real(),
      closed: integer(),
      opened: integer(),
      kept: integer(),
      gained: integer(),
      lost: integer(),
      changed_ratio: real(),
      changed_regions: integer(),
      note: text(),
      image_mismatch: text({mode: 'json'}).$type<Record<string, number>>(),
      tree: text().notNull().default(''),
      verdict: text(),
      unsettled: text(),
      broken: text(),
      broken_by: text({enum: BROKEN_BY}),
      at: integer().notNull(),
    },
    (self) => [
      ...owned(self),
      uniqueIndex('rounds_round').on(self.run_id, self.target_id, self.round),
      uniqueIndex('rounds_check').on(self.run_id, self.target_id, self.check),
      check('rounds_state', inArray(self.state, [...ROUND_STATES]).inlineParams()),
    ],
  )
  return {
    targets,
    rounds,
    missing: table(
      'missing',
      {
        seq: integer().primaryKey({autoIncrement: true}),
        target_id: text().notNull(),
        run_id: runId(),
        session: session(),
        round: integer().notNull(),
        node: text().notNull(),
        name: text(),
        kind: text({enum: COVERAGE_LISTS}).notNull(),
      },
      (self) => [
        ...byRound('missing')(self),
        check('missing_kind', inArray(self.kind, [...COVERAGE_LISTS]).inlineParams()),
      ],
    ),
    candidates: table(
      'candidates',
      {
        seq: integer().primaryKey({autoIncrement: true}),
        target_id: text().notNull(),
        run_id: runId(),
        session: session(),
        round: integer().notNull(),
        node: text().notNull(),
        selector: text().notNull(),
        score: real().notNull(),
      },
      byRound('candidates'),
    ),
    widths: table(
      'widths',
      {
        seq: integer().primaryKey({autoIncrement: true}),
        target_id: text().notNull(),
        run_id: runId(),
        session: session(),
        round: integer().notNull(),
        width: real().notNull(),
        from: text().notNull(),
        root_height: real().notNull(),
        overflow_x: integer({mode: 'boolean'}).notNull(),
      },
      byRound('widths'),
    ),
    regions: table(
      'regions',
      {
        seq: integer().primaryKey({autoIncrement: true}),
        target_id: text().notNull(),
        run_id: runId(),
        session: session(),
        round: integer().notNull(),
        x: real().notNull(),
        y: real().notNull(),
        width: real().notNull(),
        height: real().notNull(),
        id: text(),
        node: text(),
        name: text(),
        source: text(),
        overlap: real(),
        truncated: integer({mode: 'boolean'}).notNull(),
      },
      byRound('regions'),
    ),
    rows: table(
      'rows',
      {
        seq: integer().primaryKey({autoIncrement: true}),
        target_id: text().notNull(),
        run_id: runId(),
        session: session(),
        round: integer().notNull(),
        id: text(),
        node: text().notNull(),
        source: text(),
        selector: text(),
        kind: text().notNull(),
        name: text().notNull(),
        magnitude: text({enum: MAGNITUDES}).notNull(),
        width: real(),
        text: text().notNull(),
        property: text(),
        expected: text(),
        actual: text(),
        delta: real(),
        token: text(),
        component: text(),
        specifier: text(),
        kit_token: text(),
        design_token: text(),
        confidence: real(),
        margin: real(),
        repeat: integer().notNull().default(0),
        at: integer().notNull(),
      },
      (self) => [
        ...byRound('rows')(self),
        index('rows_by_node').on(self.target_id, self.node),
        check('rows_magnitude', inArray(self.magnitude, [...MAGNITUDES]).inlineParams()),
      ],
    ),
    fom: table(
      'fom',
      {
        seq: integer().primaryKey({autoIncrement: true}),
        target_id: text().notNull(),
        run_id: runId(),
        session: session(),
        id: text().notNull(),
        node: text().notNull(),
        name: text(),
        instance: text(),
        source: text(),
        site: text(),
        confidence: real().notNull(),
        margin: real().notNull(),
        round: integer().notNull(),
        voted_round: integer(),
        revoted_round: integer(),
        reason: text(),
        at: integer().notNull(),
      },
      (self) => [...byRound('fom')(self), index('fom_by_node').on(self.target_id, self.node)],
    ),
    nodes: table(
      'nodes',
      {
        seq: integer().primaryKey({autoIncrement: true}),
        target_id: text().notNull(),
        run_id: runId(),
        session: session(),
        node: text().notNull(),
        type: text().notNull(),
        name: text().notNull(),
        within: text(),
        depth: integer().notNull(),
        x: real().notNull(),
        y: real().notNull(),
        w: real().notNull(),
        h: real().notNull(),
        fill_kind: text({enum: FILL_KINDS}).notNull(),
        fill: text(),
        fill_opacity: real(),
        stroke: text(),
        stroke_weight: real(),
        radius: real(),
        font_family: text(),
        font_weight: real(),
        font_size: real(),
        line_height: real(),
        text_align: text(),
        text: text(),
        opacity: real(),
        image: integer({mode: 'boolean'}).notNull(),
        asset: text(),
        token_fill: text(),
        token_stroke: text(),
        token_radius: text(),
        token_font: text(),
        token_gap: text(),
        token_padding: text(),
      },
      owned,
    ),
    votes: table(
      'votes',
      {
        seq: integer().primaryKey({autoIncrement: true}),
        target_id: text().notNull(),
        run_id: runId(),
        session: session(),
        round: integer().notNull(),
        node: text().notNull(),
        name: text(),
        candidate: text().notNull(),
        path: text().notNull(),
        dom: real().notNull(),
        src: real().notNull(),
        cssom: real().notNull(),
        total: real().notNull(),
        won: integer({mode: 'boolean'}).notNull(),
        at: integer().notNull(),
      },
      byRound('votes'),
    ),
    tool_calls: table(
      'tool_calls',
      {
        seq: integer().primaryKey({autoIncrement: true}),
        target_id: text(),
        run_id: runId(),
        session: session(),
        tool: text().notNull(),
        round: integer(),
        check: integer(),
        input: text({mode: 'json'}).$type<unknown>(),
        reply: text({mode: 'json'}).$type<ToolReply>(),
        reply_bytes: integer(),
        duration_ms: integer().notNull(),
        error: text(),
        at: integer().notNull(),
      },
      (self) => [
        ...owned(self),
        index('tool_calls_by_round').on(self.run_id, self.round),
        check('tool_calls_tool', inArray(self.tool, TOOL_NAMES).inlineParams()),
      ],
    ),
    runs,
    labels: table(
      'labels',
      {
        seq: integer().primaryKey({autoIncrement: true}),
        target_id: text().notNull(),
        run_id: runId(),
        session: text(),
        round: integer(),
        node: text().notNull(),
        id: text(),
        verdict: text({enum: DESIGN_VERDICTS}).notNull(),
        by: text().notNull(),
        note: text(),
        at: integer().notNull().default(NOW_MS),
      },
      (self) => [...owned(self), check('verdict', sql`${self.verdict} in ('right', 'wrong')`)],
    ),
    node_components: table(
      'node_components',
      {
        seq: integer().primaryKey({autoIncrement: true}),
        target_id: text().notNull(),
        session: session(),
        run_id: runId(),
        round: integer().notNull(),
        node: text().notNull(),
        component_id: text().notNull(),
        component: text(),
        specifier: text(),
        source: text().notNull(),
      },
      (self) => [...byRound('node_components')(self), index('node_components_by_component').on(self.component_id)],
    ),
    hints: table(
      'hints',
      {
        seq: integer().primaryKey({autoIncrement: true}),
        target_id: text().notNull(),
        run_id: runId(),
        session: session(),
        round: integer().notNull(),
        node: text().notNull(),
        hint: text().notNull(),
        specifier: text(),
      },
      (self) => [...owned(self), index('hints_by_node').on(self.run_id, self.target_id, self.node)],
    ),
    notes: table(
      'notes',
      {
        seq: integer().primaryKey({autoIncrement: true}),
        target_id: text().notNull(),
        run_id: runId(),
        session: text(),
        round: integer(),
        text: text().notNull(),
        at: integer().notNull().default(NOW_MS),
      },
      owned,
    ),
  }
}

const COVERAGE_LISTS = ['missing', 'not_rendered', 'dupe', 'gone'] as const

const FILL_KINDS = ['solid', 'gradient', 'image', 'image-stack', 'none'] as const

const TOOL_NAMES = DESIGN_TOOLS.map((tool) => tool.name)

const NOW_MS = sql`(cast(unixepoch('subsec') * 1000 as integer))`

type Keyed = {run_id: SQLiteColumn; target_id: SQLiteColumn}

type Rounded = Keyed & {round: SQLiteColumn}

type Key = [SQLiteColumn, ...SQLiteColumn[]]
