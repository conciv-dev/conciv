import {sql} from 'drizzle-orm'
import {check, integer, real, text, type SQLiteTableFn} from 'drizzle-orm/sqlite-core'
import {DESIGN_VERDICTS, type Counts, type Coverage, type Design, type IdTree, type Round} from '../shared/defs.js'

export function designTables(table: SQLiteTableFn) {
  return {
    targets: table('targets', {
      target_id: text().primaryKey(),
      run_id: integer(),
      session: text().notNull(),
      link: text().notNull(),
      route: text(),
      width: real().notNull(),
      height: real().notNull(),
      scale: real().notNull(),
      design: text({mode: 'json'}).$type<Design>().notNull(),
      ids: text({mode: 'json'}).$type<IdTree>(),
      image: text().notNull(),
      at: integer().notNull(),
    }),
    rounds: table('rounds', {
      seq: integer().primaryKey({autoIncrement: true}),
      target_id: text().notNull(),
      run_id: integer(),
      round: integer().notNull(),
      counts: text({mode: 'json'}).$type<Counts>().notNull(),
      coverage: text({mode: 'json'}).$type<Coverage>().notNull(),
      reflow: text({mode: 'json'}).$type<Round['reflow']>().notNull(),
      pixel_share: real(),
      tree: text().notNull(),
      live: text(),
      diff: text(),
      at: integer().notNull(),
    }),
    rows: table('rows', {
      seq: integer().primaryKey({autoIncrement: true}),
      target_id: text().notNull(),
      run_id: integer(),
      round: integer().notNull(),
      id: text(),
      node: text().notNull(),
      source: text(),
      selector: text(),
      kind: text().notNull(),
      name: text().notNull(),
      magnitude: text().notNull(),
      width: real(),
      text: text().notNull(),
      confidence: real(),
      margin: real(),
      at: integer().notNull(),
    }),
    fom: table('fom', {
      seq: integer().primaryKey({autoIncrement: true}),
      target_id: text().notNull(),
      run_id: integer(),
      id: text().notNull(),
      node: text().notNull(),
      instance: text(),
      source: text(),
      confidence: real().notNull(),
      margin: real().notNull(),
      round: integer().notNull(),
      revoted_round: integer(),
      reason: text(),
      at: integer().notNull(),
    }),
    votes: table('votes', {
      seq: integer().primaryKey({autoIncrement: true}),
      target_id: text().notNull(),
      run_id: integer(),
      round: integer().notNull(),
      node: text().notNull(),
      candidate: text().notNull(),
      path: text().notNull(),
      dom: real().notNull(),
      src: real().notNull(),
      cssom: real().notNull(),
      total: real().notNull(),
      won: integer({mode: 'boolean'}).notNull(),
      at: integer().notNull(),
    }),
    tool_calls: table('tool_calls', {
      seq: integer().primaryKey({autoIncrement: true}),
      target_id: text(),
      run_id: integer(),
      tool: text().notNull(),
      input: text({mode: 'json'}).$type<unknown>(),
      reply_bytes: integer(),
      duration_ms: integer().notNull(),
      error: text(),
      at: integer().notNull(),
    }),
    runs: table('runs', {
      run_id: integer().primaryKey({autoIncrement: true}),
      target_id: text(),
      model: text().notNull(),
      prompt_head: text().notNull(),
      started: integer().notNull(),
      ended: integer(),
      cost: real(),
      verdict: text(),
    }),
    labels: table(
      'labels',
      {
        seq: integer().primaryKey({autoIncrement: true}),
        target_id: text().notNull(),
        run_id: integer(),
        round: integer(),
        node: text().notNull(),
        id: text(),
        verdict: text({enum: DESIGN_VERDICTS}).notNull(),
        by: text().notNull(),
        note: text(),
        at: integer()
          .notNull()
          .$defaultFn(() => Date.now()),
      },
      (self) => [check('verdict', sql`${self.verdict} in ('right', 'wrong')`)],
    ),
    notes: table('notes', {
      seq: integer().primaryKey({autoIncrement: true}),
      target_id: text().notNull(),
      run_id: integer(),
      round: integer(),
      text: text().notNull(),
      at: integer()
        .notNull()
        .$defaultFn(() => Date.now()),
    }),
  }
}
